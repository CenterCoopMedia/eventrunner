#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');

const CODE_EXTENSIONS = new Set(['.cjs', '.js', '.jsx', '.mjs', '.ts', '.tsx']);
const SCANNED_EXTENSIONS = new Set([...CODE_EXTENSIONS, '.html', '.json', '.md']);

const ROOT_FILES = Object.freeze([
  'README.md',
  'apps/web/README.md',
  'functions/README.md',
  'scripts/README.md',
  'docs/index.html',
  'docs/ADMIN_GUIDE.md',
  'docs/CLIENT_ONBOARDING.md',
  'docs/DEPLOY_RUNBOOK.md',
  'docs/EVENTBRITE_VERIFICATION.md',
  'docs/POSTMARK_PROVISIONING.md',
  'docs/ROADMAP.md',
  'scripts/lib/demo-event.cjs',
  'scripts/lib/seed.cjs',
]);

const RECURSIVE_ROOTS = Object.freeze([
  'apps/web/src',
  'functions/src',
  'docs/handbook',
  'design/tokens/presets',
]);

const BLOCKED_RULES = Object.freeze([
  {
    id: 'stock-promotion',
    pattern:
      /\b(?:seamless(?:ly)?|robust|effortless(?:ly)?|unlock(?:s|ed|ing)?|elevate(?:s|d|ing)?|empower(?:s|ed|ing)?|delve(?:s|d|ing)?|transformative|revolutionary)\b/giu,
    guidance: 'State the action, result, or limit instead.',
  },
  {
    id: 'marketing-superlative',
    pattern:
      /\b(?:cutting[- ]edge|game[- ]changing|world[- ]class|best[- ]in[- ]class|AI[- ]powered)\b/giu,
    guidance: 'Replace the claim with a specific supported fact.',
  },
  {
    id: 'rhetorical-frame',
    pattern:
      /\b(?:not just|more than just|whether you(?: are|'re)|in today(?:'|’)?s|at its core)\b/giu,
    guidance: 'Start with the required fact or instruction.',
  },
  {
    id: 'assistant-meta',
    pattern:
      /\b(?:AI assistant|AI[- ]generated|generated by AI|Claude(?: Code)?|vibe[- ]coded)\b/giu,
    guidance: 'Remove process commentary from current user-facing copy.',
  },
  {
    id: 'design-metaphor',
    pattern:
      /\b(?:reads as|read as|story written|on its feet|paper of record|on a good day|wears|dressed in)\b/giu,
    guidance: 'Describe the visible layout or behavior directly.',
  },
  {
    id: 'filler',
    pattern: /\b(?:simply|obviously|of course)\b/giu,
    guidance: 'Delete the filler word or state the reason.',
  },
  {
    id: 'long-dash',
    pattern: /—|&mdash;|&#8212;/gu,
    guidance: 'Use a full stop, comma, colon, or parentheses.',
  },
]);

function isTestOrGenerated(relativePath) {
  const normalized = relativePath.split(path.sep).join('/');
  return (
    normalized.includes('/generated/') ||
    normalized.includes('/__tests__/') ||
    /(?:^|\/)(?:dist|node_modules|coverage)\//u.test(normalized) ||
    /\.(?:test|spec)\.[^.]+$/u.test(normalized) ||
    normalized === 'apps/web/src/setupTests.js' ||
    normalized === 'apps/web/src/admin/presetCopy.js'
  );
}

function walk(relativeRoot) {
  const absoluteRoot = path.join(ROOT, relativeRoot);
  if (!fs.existsSync(absoluteRoot)) return [];
  const files = [];
  for (const entry of fs.readdirSync(absoluteRoot, { withFileTypes: true })) {
    const child = path.join(relativeRoot, entry.name);
    if (entry.isDirectory()) files.push(...walk(child));
    else if (
      entry.isFile() &&
      SCANNED_EXTENSIONS.has(path.extname(entry.name)) &&
      !isTestOrGenerated(child)
    ) {
      files.push(child);
    }
  }
  return files;
}

function collectFiles() {
  const files = new Set();
  for (const relativePath of ROOT_FILES) {
    if (fs.existsSync(path.join(ROOT, relativePath))) files.add(relativePath);
  }
  for (const relativeRoot of RECURSIVE_ROOTS) {
    for (const relativePath of walk(relativeRoot)) files.add(relativePath);
  }
  return [...files].sort();
}

// Remove JavaScript comments while preserving strings, line breaks, and
// character positions. This keeps findings on the source line a user edits.
function stripCodeComments(source) {
  let output = '';
  let state = 'code';
  let escaped = false;

  for (let index = 0; index < source.length; index += 1) {
    const char = source[index];
    const next = source[index + 1];

    if (state === 'line-comment') {
      if (char === '\n') {
        output += '\n';
        state = 'code';
      } else output += ' ';
      continue;
    }

    if (state === 'block-comment') {
      if (char === '*' && next === '/') {
        output += '  ';
        index += 1;
        state = 'code';
      } else output += char === '\n' ? '\n' : ' ';
      continue;
    }

    if (state === 'single' || state === 'double' || state === 'template') {
      output += char;
      if (escaped) {
        escaped = false;
        continue;
      }
      if (char === '\\') {
        escaped = true;
        continue;
      }
      if (
        (state === 'single' && char === "'") ||
        (state === 'double' && char === '"') ||
        (state === 'template' && char === '`')
      ) {
        state = 'code';
      }
      continue;
    }

    if (char === '/' && next === '/') {
      output += '  ';
      index += 1;
      state = 'line-comment';
    } else if (char === '/' && next === '*') {
      output += '  ';
      index += 1;
      state = 'block-comment';
    } else {
      output += char;
      if (char === "'") state = 'single';
      else if (char === '"') state = 'double';
      else if (char === '`') state = 'template';
    }
  }

  return output;
}

function textToScan(source, relativePath) {
  const extension = path.extname(relativePath);
  if (CODE_EXTENSIONS.has(extension)) return stripCodeComments(source);
  if (extension === '.html') {
    return source.replace(/<!--[\s\S]*?-->/gu, (comment) =>
      comment.replace(/[^\n]/gu, ' '),
    );
  }
  return source;
}

function lineNumberAt(source, index) {
  let line = 1;
  for (let cursor = 0; cursor < index; cursor += 1) {
    if (source[cursor] === '\n') line += 1;
  }
  return line;
}

function excerptAt(source, index) {
  const lineStart = source.lastIndexOf('\n', index - 1) + 1;
  const lineEndValue = source.indexOf('\n', index);
  const lineEnd = lineEndValue === -1 ? source.length : lineEndValue;
  return source.slice(lineStart, lineEnd).trim().replace(/\s+/gu, ' ').slice(0, 180);
}

function findFindings(source, relativePath, rules = BLOCKED_RULES) {
  const scanned = textToScan(source, relativePath);
  const findings = [];

  for (const rule of rules) {
    rule.pattern.lastIndex = 0;
    for (const match of scanned.matchAll(rule.pattern)) {
      findings.push({
        path: relativePath,
        line: lineNumberAt(scanned, match.index),
        rule: rule.id,
        match: match[0],
        guidance: rule.guidance,
        excerpt: excerptAt(source, match.index),
      });
    }
  }

  return findings.sort(
    (left, right) => left.line - right.line || left.rule.localeCompare(right.rule),
  );
}

function run() {
  const files = collectFiles();
  const findings = [];

  for (const relativePath of files) {
    const source = fs.readFileSync(path.join(ROOT, relativePath), 'utf8');
    findings.push(...findFindings(source, relativePath));
  }

  if (findings.length === 0) {
    console.log(`copy-style: checked ${files.length} files; no blocked patterns found.`);
    return;
  }

  console.error(`copy-style: found ${findings.length} blocked pattern(s) in ${files.length} files.`);
  for (const finding of findings) {
    console.error(
      `${finding.path}:${finding.line} [${finding.rule}] ${JSON.stringify(finding.match)}\n` +
        `  ${finding.excerpt}\n` +
        `  ${finding.guidance}`,
    );
  }
  process.exitCode = 1;
}

if (require.main === module) run();

module.exports = {
  BLOCKED_RULES,
  collectFiles,
  findFindings,
  stripCodeComments,
  textToScan,
};
